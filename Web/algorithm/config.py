# ---------------------------------------------------------------
# 코드값(영문) <-> 화면 표시용 한글명.
# 백엔드/프론트는 영문 코드값("empathy" 등)으로 주고받고,
# 로그나 사람이 볼 때만 한글명을 씁니다.
CATEGORIES = {
    "empathy": "공감",
    "laughter": "웃음",
    "info": "정보",
    "touching": "감동",
}

# 카테고리 1개당 Claude 가 뽑는 최대 후보 구간 수
PER_CATEGORY_MAX = 3


# ---------------------------------------------------------------
# 클립 개수 규칙
# ---------------------------------------------------------------
# 사용자가 고른 카테고리 수 -> 최종 목표 클립 수.
# (카테고리당 3개씩이지만 4개일 때는 12개가 아니라 9개로 캡)
CLIP_COUNT_MAP = {
    1: 3,
    2: 6,
    3: 9,
    4: 9,
}


# ---------------------------------------------------------------
# 후처리 규칙
# ---------------------------------------------------------------
# dedup: 두 후보 구간의 시간이 이 비율 이상 겹치면 "같은 순간"으로 보고 병합.
# (예: 웃음에서도 뽑히고 공감에서도 뽑힌 구간 -> 하나로 합치고 category 두 개 부여)
DEDUP_OVERLAP_RATIO = 0.5

# 클립 길이(초) 권장 범위. 벗어나도 버리지 않고 내부 점검용으로만 사용.
CLIP_MIN_SEC = 30
CLIP_MAX_SEC = 90


# ---------------------------------------------------------------
# 헬퍼
# ---------------------------------------------------------------
def get_target_clip_count(num_categories: int) -> int:
    """선택한 카테고리 수에 맞는 목표 클립 수를 반환한다."""
    return CLIP_COUNT_MAP.get(num_categories, 9)


def validate_categories(categories: list) -> None:
    """
    백엔드가 넘긴 categories 가 유효한지 입구에서 검사한다.
    문제가 있으면 예외를 던져서(그물망) 백엔드가 failed 로 처리하게 한다.
    """
    if not categories:
        raise ValueError("categories 가 비어 있습니다. 최소 1개 카테고리가 필요합니다.")

    if len(categories) > len(CATEGORIES):
        raise ValueError(f"카테고리는 최대 {len(CATEGORIES)}개까지 가능합니다.")

    for c in categories:
        if c not in CATEGORIES:
            raise ValueError(
                f"알 수 없는 카테고리: '{c}' (가능: {list(CATEGORIES.keys())})"
            )