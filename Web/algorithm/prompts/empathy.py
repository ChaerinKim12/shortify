"""
===============================================================
공감 카테고리 프롬프트 (prompts/empathy.py)  담당: 김채린
===============================================================
이 파일은 "공감 카테고리의 선정 기준"만 담습니다.
역할/입력설명/사고과정/출력형식 등 공통 부분은 base.py 에 있고,
build_segment_prompt() 가 이 기준을 {category_prompt} 자리에 끼워 넣습니다.

[음성 태그]
  base.py 와 동일한 4종만 사용합니다:
  [음량↑/↓] [피치↑/↓] [말빠름/말느림] [무음]
===============================================================
"""

EMPATHY_CATEGORY_PROMPT = """
시청자(20대 대학생/취준생)가 영상을 보다가
스크롤을 멈추고 "어 나도..." 가 자동으로 나오는 구간.

꾸미지 않은 날것의 현실 + 보편적 경험/감정이 핵심.

[훅 기준 - 첫 3초에 이게 있어야 공감 후보]
- 보편적 상황 선언: "나만 그런 거 아니지?", "다들 이러지 않나?"
- 자기고백 시작: "솔직히", "사실 나"
- 일상 실패 톤: "또 망했어", "결국 또"
- 감정 직격: "아 진짜 모르겠다", "왜 이러지"

[자막 패턴]
경험 공감 (20대 일상 키워드):
시험/과제/벼락치기/취업/면접/스펙/자취/혼밥/
용돈/통장/카톡/연애/썸/친구관계/부모님 눈치/
무기력/번아웃/잠/늦잠/미루기

감정 공감:
- 무기력: "아무것도 하기 싫다", "그냥", "모르겠다"
- 자책: "왜 나는", "나만 이런가", "또 이래"
- 억울/지침: "열심히 했는데", "왜 이렇게까지"
- 작은 행복: "이게 뭐라고", "별거 아닌데 좋다"

자조적 유머 (포함 O):
- 자기비하 + 웃음: "아 또 시켰네 ㅋㅋ", "나란 인간"
- 포기형 농담: "그냥 이렇게 살래", "어쩔 수 없지"

[음성 힌트 해석]
진심 고백 신호:
- [말느림] + [음량↓] + 자기고백 키워드 동반
- [무음] 1초 이상 -> 직후 발화 (망설이다 꺼낸 말)

감정 격발 신호:
- [말빠름] + [음량↑] -> 격하게 토로
- [말빠름] 후 갑자기 [말느림] -> 흥분->진지 전환점

주의 - 다음은 공감 아님:
- [말느림] + [음량↓] 만 있고 키워드 없음 -> 졸린 말투
- 같은 톤 일정 유지 -> 정보 전달 가능성

[화자 분리 활용]
- 한 화자가 길게 고백/토로하는 구간 우선
- 화자끼리 "맞아 맞아" 동조하는 구간도 공감 신호
- 단, 짧게 주고받는 대화는 단독 완결성 떨어져서 후순위

[단독 완결성]
- 30~90초 안에 상황 -> 감정 -> 마무리가 들어가야 함
- "근데 그게..." "아까 말한..." 등 앞 맥락 의존 표현 시작은 제외
- 클립만 봐도 무슨 상황인지 이해 가능해야 함

[공감 고유 오탐 방지]
- 감동과 구분:
  공감  = "나도 그래" (시청자가 자기 경험을 투영)
  감동  = "저 말/저 순간이 뭉클하다" (정서적 울림/위로)
  자기 투영이 핵심이면 공감, 위로/뭉클이 핵심이면 감동에 양보
- 자막에 공감 키워드는 있지만 음성힌트가 평탄 -> 감정 없는 형식적 발화 (제외)
"""


def get_empathy_prompt() -> str:
    """공감 카테고리 선정 기준 본문을 반환한다."""
    return EMPATHY_CATEGORY_PROMPT.strip()