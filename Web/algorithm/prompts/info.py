"""
===============================================================
정보 카테고리 프롬프트 (prompts/info.py)  담당: 김지연
===============================================================
이 파일은 "정보 카테고리의 선정 기준"만 담습니다.
공통 부분(역할/입력설명/출력형식)은 base.py 에 있습니다.

기반 이론: 정보 격차 이론 (Loewenstein 1994).
정보 범위 = 노하우/팁 + 제품 정보(리뷰/언박싱/하울) + 사실 전달.

[중요 - 음성 신호 표기 변경]
  원본 기준은 [음량↑↑], [음색밝음/어두움], [날카로움], 🔥, 💤 등
  우리 파이프라인이 만들지 않는 태그를 썼습니다.
  audio_features.py 가 주는 4종 태그로 정리했습니다:
    [음량↑/↓] [피치↑/↓] [말빠름/말느림] [무음]
    - [음량↑↑]        -> [음량↑] (우리는 강도 2단계 없음)
    - [빠름]/[느림]    -> [말빠름]/[말느림]
    - 💤(무음 많음)    -> [무음]
    - [음색밝음/어두움], [날카로움] -> 우리가 만들지 않는 태그라 제거
  히트맵(원본 🔥)은 음성 태그가 아니라 별도 데이터로 들어옵니다.
  URL 영상일 때만 프롬프트에 포함되므로 "(URL 영상일 때만)"으로 표기했습니다.
===============================================================
"""

INFO_CATEGORY_PROMPT = """
시청자가 '이거 몰랐다 / 사야겠다 / 써먹어야지' 하고 저장 버튼을 누르는
구간을 찾는다. 정보의 형태는 세 가지를 모두 포함한다:
  - 노하우/팁 (공부법, 라이프핵, 꿀팁)
  - 제품 정보 (리뷰, 언박싱, 하울, 추천, 비교)
  - 사실 전달 (지식, 뉴스, 분석)

[핵심 원리 - 정보 격차 이론]
사람은 '내가 아는 것'과 '알고 싶은 것' 사이의 격차를 인지하는 순간
그 해소를 위해 시청을 계속한다. 정보 클립은 이 격차를 한 문장 안에
만들고, 같은 구간 안에서 해소까지 끝내는 구간을 찾는 작업이다.

[필수 조건 - 셋 다 충족해야 채택]
1) 격차 생성: 구간 첫 10초 안에 '몰랐던 것'을 알게 될 가능성을 암시.
   훅 발화 또는 새로운 대상(제품 등) 등장.
2) 격차 해소: 구간 안에서 결론/팁/스펙/사용법이 명확히 완결.
   ('자세한 건 다음 영상에서' 식으로 미루는 구간 X)
3) 단독 완결성: 원본 영상 맥락 없이 봐도 이해 가능.

[강한 신호 - 텍스트 패턴]
A. 격차 유발 훅 (노하우/사실형)
   - '사실은', '알고 보면', '의외로', '이거 모르면 손해'
   - '대부분 ~한다고 생각하는데', '~인 줄 알았는데'
   - '~할 때 절대 ~하지 마세요', '딱 하나만 기억하세요'
B. 답이 따라붙는 구조
   - '이유가 뭐냐면', '핵심은', '결론부터 말하면'
   - 'N가지 ~', 'N번 ~', 'A 먼저, B 다음에'
C. 제품 정보 신호 (리뷰/하울/언박싱형)
   - 모델명/브랜드명/가격대 ('이거 N만원', 'OO 제품')
   - 구체 스펙 ('지퍼 2개', '용량 N리터', 'USB-C', 'N시간 지속')
   - 사용 시나리오 ('~할 때 쓰려고', '~한 사람한테 추천')
   - 비교/대조 ('전에 쓰던 거 vs 이거', 'A보다 B가 ~')
   - 만족도 단서 ('실패한 적 없어', '진짜 잘 산 것 같아')
D. 구체성 신호 (공통)
   - 수치/퍼센트/시간 단위 (3분, 30%, 5만원)
   - 단계/순서 명시 (첫째·둘째 / 1단계·2단계)

[음성 신호 - 자막 옆 4종 태그 활용]
- [음량↑] : 핵심 결론/스펙을 강조하는 순간.
  구체 정보(수치/모델명/팁)와 동시 발생 시 강한 채택 신호.
  단순 감탄('와','대박')에만 붙으면 무시.
- [말빠름] : 정보 전달 모드의 전형적 시그널(긍정).
  자신감 있게 내용을 쏟아내는 구간.
- [말느림] : 양면적. 결론/주의사항을 또박또박 강조하면 긍정,
  말 끌며 시간만 끌면 부정. 텍스트와 함께 판단.
- [무음]   : 비중이 크면(구간 30% 초과) 정보 밀도 낮음 -> 제외 신호.

[교차 검증 - 채택 전 필수]
각 후보에 대해 아래 신호를 동시 확인:
(1) 텍스트: 격차 훅 / 제품 정보 / 구체성 중 최소 1개
(2) 음성  : [음량↑] 또는 [말빠름], 또는 [말느림]+결론/주의사항 중 1개
(3) 히트맵 (URL 영상일 때만): 영상 내 상위 30% 구간

채택 룰:
- 3개 중 2개 이상 충족 -> 채택
- 히트맵 없는 영상(로컬 업로드)은 텍스트 + 음성 둘 다 충족해야 채택

[복합 신호 우선순위]
높음: [음량↑] + 구체 수치/스펙        (핵심 강조)
높음: [말빠름] + 격차 유발 훅          (정보 전달 + 호기심)
높음: 히트맵 상위 + 텍스트 + 음성 동시 (시청자 검증된 핵심, URL 영상)
중간: [음량↑] + [말빠름] 동시          (열정적 설명)
중간: [말느림] + 결론/주의사항         (또박또박 강조)
낮음: 음성만 강하고 텍스트 약함        (의심)

[정보 고유 오탐 방지 - 정보 0인 구간]
- 의미 없는 감탄 반복만 ('와 예뻐', '좋아요', '대박')
- 추상적 조언만 ('열심히 하세요', '꾸준히 하세요')
- 격차만 만들고 답은 다음 구간으로 넘김
- 화자 개인사만 있고 시청자가 가져갈 정보 0
- [무음] 비중 30% 초과 구간
- 협찬/광고 디스클로저 자체 ('이 영상은 ~ 협찬받았습니다')

[하울/언박싱/리뷰 영상 특별 가이드]
이런 영상은 전체가 정보 대상이다. '좋다/예쁘다' 감탄만 있는 구간이 아니라
구체 특징('지퍼 2개라서 분리 수납'), 구매 판단 정보('이 가격에 이 퀄리티면'),
사용 시연('실제로 들어보니까'), 비교('전에 산 거랑 비교하면')가
충분한 구간을 우선 선정. 감탄과 정보가 섞여도 정보 비중이 높으면 채택.
이때 [음량↑]이 '정보 부분'에 붙었는지 '감탄 부분'에 붙었는지 구분:
  '용량 50ml [음량↑]' = 정보 강조 (채택), '예뻐요 [음량↑]' = 단순 감탄 (가치 낮음)

[가산점]
+ 첫 3초 안에 다룰 정보의 윤곽이 잡힘 ('오늘 알려드릴 3가지', '이 가방의 핵심은')
+ 구간 끝에 한 줄 요약/평가/추천
+ 보편 관심사 (돈/건강/시간/관계/일/쇼핑/뷰티/IT)
+ 제품 영상: 말로만 설명 X, 사용 장면/시연 포함
"""


def get_info_prompt() -> str:
    """정보 카테고리 선정 기준 본문을 반환한다."""
    return INFO_CATEGORY_PROMPT.strip()