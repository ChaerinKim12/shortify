"""
===============================================================
웃음 카테고리 프롬프트 (prompts/laughter.py)  담당: 양세은
===============================================================
이 파일은 "웃음 카테고리의 선정 기준"만 담습니다.
공통 부분(역할/입력설명/출력형식)은 base.py 에 있습니다.

[중요 - 음성 신호 표기 변경]
  원본 기준은 emotion_group / emotion_score / db_relative(top_10pct 등)
  같은 "raw 수치 필드"를 Claude 가 직접 본다고 가정했습니다.
  그러나 우리 파이프라인은 그런 raw 필드를 Claude 에게 주지 않고,
  audio_features.py 가 발화 옆에 4종 태그만 붙여서 줍니다:
    [음량↑/↓] [피치↑/↓] [말빠름/말느림] [무음]
  그래서 원본의 raw 신호를 의미가 같은 4종 태그로 번역했습니다.
    - emotion_score 높음(놀람/당황)  -> [피치↑] (+ [음량↑])
    - db_relative top_10pct(음량 급상승) -> [음량↑]
    - 놀람 + 음량 피크 동시            -> [음량↑] + [피치↑] 동시
  웃음 메커니즘(자기폭로/자기모순/예상뒤집힘 등)은 원본 그대로 보존했습니다.
===============================================================
"""

LAUGHTER_CATEGORY_PROMPT = """
시청자가 영상을 보다가 실제로 소리 내어 웃거나, 입꼬리가 올라가거나,
"ㅋㅋ" 댓글을 달고 싶어지는 구간.

[웃음을 유발하는 6가지 메커니즘]
1) 자기 폭로형 웃음
   - 화자가 자신의 한심한/부끄러운/극단적인 일상을 솔직하게 털어놓음
   - 예: "어제 12시간 누워있었어요", "씻지도 않고 3일째예요"
   - 핵심: 시청자가 '나도 저런 적 있어'라며 공감하면서 웃는 종류
2) 자기 모순형 웃음
   - 진지하게 말하다가 본인이 모순을 발견하거나, 말이 꼬임
   - 예: "긍정적으로 살아야지... 근데 일어나기 싫네",
     "다이어트 시작했어요. 어제부터 디저트만 먹어요"
   - 핵심: 본인이 본인 말에 당황하는 순간
3) 예상 뒤집힘
   - 시청자가 A를 기대하고 있는데 B가 나옴
   - 예: 진지한 분위기 -> 갑자기 엉뚱한 결론
   - 텍스트 신호: "근데", "사실은", "알고 보니까" 이후 톤 변화
4) 과장된 표현/리액션
   - 평범한 상황에 과한 단어 사용
   - 예: "현타가 세게 왔어요", "얼굴이 폭발했어요", "마음이 부서졌어요"
   - 음성 신호: 평소보다 [음량↑], 흥분하면 [피치↑] 동반
5) 자막 텍스트 신호
   - ㅋㅋㅋ, 하하, 푸하 등 명시적 웃음 표기
   - "미쳤다", "어이없네", "이게 뭐야" 같은 어이없음 표현
   - "진짜?", "헐", "와" 같은 놀람 후 이어지는 맥락
6) 음성 신호 (자막 옆 4종 태그 활용)
   - [피치↑] (+ [음량↑]) : 놀람/당황/격양 -> 웃음 후보 강신호
   - [음량↑] : 음량 급상승 (강조/외침/빵 터지는 순간)
   - [말빠름] : 신나서 쏟아내거나 흥분한 구간
   - [음량↑] 와 [피치↑] 가 동시에 붙은 발화 = 1순위 후보

[필수 조건]
- 구간 시작 3초 안에 위 신호 중 하나가 등장해야 함 (스와이프 방지)
- 맥락 없이 단독으로 봐도 웃을 수 있어야 함
- 화자가 진심으로 한 말이어야 함 (연출/억지 X)

[웃음 고유 오탐 방지 - 다음은 웃음 구간이 아님]
- 자막에 'ㅋㅋ'만 있고 내용이 평범한 대화
- 화자가 다른 사람 얘기를 전달만 하는 구간 (본인의 일이어야 함)
- 웃긴 결과만 있고 빌드업이 없는 구간 (직전 기대감 구간 함께 포함 필수)
- 단순 욕설/비속어 (자연스러운 흐름 속 욕설은 OK)
- 자막은 웃긴 듯한데 음성힌트가 평탄 -> 텍스트만 자극적이고 실제론 안 웃김

[웃음 강도 우선순위]
높음: 자기 폭로 + 자기 모순이 결합된 구간
      (예: "긍정적이어야지 하면서 또 누웠어요")
중간: 과장된 표현 + [음량↑] 또는 [피치↑] 동시 발생
낮음: 단순 ㅋㅋㅋ만 있는 구간
"""


def get_laughter_prompt() -> str:
    """웃음 카테고리 선정 기준 본문을 반환한다."""
    return LAUGHTER_CATEGORY_PROMPT.strip()